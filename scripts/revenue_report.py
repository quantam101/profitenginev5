#!/usr/bin/env python3
"""Daily revenue snapshot — pulls from Stripe + MongoDB, logs to GitHub Issues.

Usage: python scripts/revenue_report.py
Env: STRIPE_SECRET_KEY, MONGO_URI (optional), GITHUB_TOKEN, GITHUB_REPO
"""

import os
import json
import datetime
import urllib.request
import urllib.parse
import urllib.error

STRIPE_KEY = os.environ.get("STRIPE_SECRET_KEY", "")
MONGO_URI = os.environ.get("MONGO_URI", "")
GITHUB_TOKEN = os.environ.get("GITHUB_TOKEN", "")
GITHUB_REPO = os.environ.get("GITHUB_REPO", "quantam101/profitenginev5")

PRODUCTS = {
    "tokenforge": {"name": "TokenForge API", "plans": {"starter": 19, "pro": 99, "enterprise": 499}},
    "profitengine": {"name": "ProfitEngine Studio", "plans": {"studio_monthly": 149, "studio_annual": 1490 / 12}},
}


def stripe_request(path: str) -> dict:
    req = urllib.request.Request(
        f"https://api.stripe.com/v1{path}",
        headers={"Authorization": f"Bearer {STRIPE_KEY}"},
    )
    try:
        resp = urllib.request.urlopen(req, timeout=15)
        return json.loads(resp.read())
    except urllib.error.HTTPError as e:
        return {"error": str(e), "data": []}


def get_revenue_last_30d() -> dict:
    now = int(datetime.datetime.utcnow().timestamp())
    start = now - 30 * 86400
    data = stripe_request(f"/charges?created[gte]={start}&limit=100&expand[]=data.metadata")
    charges = data.get("data", [])
    total = sum(c["amount"] for c in charges if c.get("paid")) / 100
    by_plan: dict[str, float] = {}
    for c in charges:
        if not c.get("paid"):
            continue
        plan = c.get("metadata", {}).get("plan_id", "unknown")
        by_plan[plan] = by_plan.get(plan, 0) + c["amount"] / 100
    return {"total_usd": total, "by_plan": by_plan, "charge_count": len([c for c in charges if c.get("paid")])}


def get_active_subscriptions() -> dict:
    data = stripe_request("/subscriptions?status=active&limit=100")
    subs = data.get("data", [])
    mrr = sum(s.get("plan", {}).get("amount", 0) for s in subs) / 100
    return {"count": len(subs), "mrr_usd": mrr}


def get_recent_events() -> list:
    data = stripe_request("/events?limit=20&type=payment_intent.succeeded")
    events = data.get("data", [])
    return [
        {
            "ts": datetime.datetime.utcfromtimestamp(e["created"]).strftime("%Y-%m-%d %H:%M"),
            "amount": e.get("data", {}).get("object", {}).get("amount", 0) / 100,
            "currency": e.get("data", {}).get("object", {}).get("currency", "usd").upper(),
        }
        for e in events
    ]


def format_report(revenue: dict, subs: dict, events: list) -> str:
    date = datetime.datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    target = 25000
    total_30d = revenue.get("total_usd", 0)
    mrr = subs.get("mrr_usd", 0)
    sub_count = subs.get("count", 0)
    progress_pct = min(100, (total_30d / target) * 100)
    bar_filled = int(progress_pct / 5)
    bar = "█" * bar_filled + "░" * (20 - bar_filled)

    lines = [
        f"## 💰 Revenue Report — {date}",
        "",
        f"### Progress to $25,000 Target",
        f"```",
        f"[{bar}] {progress_pct:.1f}%",
        f"30d Revenue: ${total_30d:,.2f}  |  MRR: ${mrr:,.2f}/mo  |  Active subs: {sub_count}",
        f"```",
        "",
        "### Revenue by Plan (last 30d)",
        "",
    ]

    if revenue.get("by_plan"):
        for plan, amt in sorted(revenue["by_plan"].items(), key=lambda x: -x[1]):
            lines.append(f"- **{plan}**: ${amt:,.2f}")
    else:
        lines.append("- No paid conversions yet — SSL fix required for TokenForge")

    lines += [
        "",
        "### Recent Conversions",
        "",
    ]
    if events:
        for e in events[:5]:
            lines.append(f"- {e['ts']} — **${e['amount']:.2f} {e['currency']}**")
    else:
        lines.append("- No recent conversions")

    lines += [
        "",
        "### Action Items",
        "",
        f"- [ ] MRR target this week: **${max(500, mrr * 1.2):,.0f}** ({'+20%' if mrr > 0 else 'first paid user'})",
        "- [ ] TokenForge SSL fix — enables all paid conversions",
        "- [ ] Referral campaign — each referral = $19-99 upgrade potential",
        "- [ ] Tradegate2 enterprise outreach — $299-999/mo per customer",
        "",
        "---",
        "_Auto-generated by revenue_report.py_",
    ]
    return "\n".join(lines)


def post_to_github(body: str, label: str = "revenue-report") -> None:
    if not GITHUB_TOKEN:
        print("No GITHUB_TOKEN — skipping GitHub post")
        print(body)
        return

    owner, repo = GITHUB_REPO.split("/")
    # Find existing open report issue this month
    month = datetime.datetime.utcnow().strftime("%Y-%m")
    title = f"💰 Revenue Report {month}"

    list_req = urllib.request.Request(
        f"https://api.github.com/repos/{owner}/{repo}/issues?state=open&labels={label}&per_page=1",
        headers={"Authorization": f"token {GITHUB_TOKEN}", "Accept": "application/vnd.github.v3+json"},
    )
    try:
        issues = json.loads(urllib.request.urlopen(list_req, timeout=10).read())
    except Exception:
        issues = []

    if issues:
        # Add comment to existing issue
        comment_req = urllib.request.Request(
            f"https://api.github.com/repos/{owner}/{repo}/issues/{issues[0]['number']}/comments",
            data=json.dumps({"body": body}).encode(),
            headers={"Authorization": f"token {GITHUB_TOKEN}", "Accept": "application/vnd.github.v3+json", "Content-Type": "application/json"},
            method="POST",
        )
        urllib.request.urlopen(comment_req, timeout=10)
        print(f"Posted comment to issue #{issues[0]['number']}")
    else:
        # Create new issue
        create_req = urllib.request.Request(
            f"https://api.github.com/repos/{owner}/{repo}/issues",
            data=json.dumps({"title": title, "body": body, "labels": [label]}).encode(),
            headers={"Authorization": f"token {GITHUB_TOKEN}", "Accept": "application/vnd.github.v3+json", "Content-Type": "application/json"},
            method="POST",
        )
        result = json.loads(urllib.request.urlopen(create_req, timeout=10).read())
        print(f"Created issue #{result['number']}: {result['html_url']}")


if __name__ == "__main__":
    print("Fetching revenue data...")
    if STRIPE_KEY and STRIPE_KEY.startswith("sk_"):
        revenue = get_revenue_last_30d()
        subs = get_active_subscriptions()
        events = get_recent_events()
    else:
        print("No Stripe key — using zeros")
        revenue = {"total_usd": 0, "by_plan": {}, "charge_count": 0}
        subs = {"count": 0, "mrr_usd": 0}
        events = []

    report = format_report(revenue, subs, events)
    post_to_github(report)
